			if (knobValue != num)
			{
				OnKnobChanged(EventArgs.Empty);
			}
		}
		if (valueType == "div10")
		{
			int num2 = knobValue;
			if (knobMinimum < 0 && knobMaximum > 0)
			{
				knobValue = 0;
			}
			if (knobValue != num2)
			{
				OnKnobChanged(EventArgs.Empty);
			}
		}
	}

	protected override void OnKeyDown(KeyEventArgs e)
	{
		_ = (decimal)knobValue;
		_ = ValueDB;
	}

	protected override void OnMouseMove(MouseEventArgs e)
	{
		if (!thumbed)
		{
			return;
		}
		if (startArcX == -1)
		{
			GraphicsPath graphicsPath = new GraphicsPath();
			graphicsPath.AddEllipse(new Rectangle(base.Width / 2 - radius + 2, offsetY + 2, radius * 2, radius * 2));
			Region region = new Region(graphicsPath);
			region.Intersect(new Rectangle(e.Location, new Size(1, 1)));
			if (!region.IsEmpty(CreateGraphics()))
			{
				return;
			}
			startArcX = e.X;
			startArcY = e.Y;
			startAngle = Math.Atan2(startArcY - startY, startArcX - startX);
			if (startAngle <= 0.0)
			{
				startAngle = Math.PI * 2.0 + startAngle;
			}
			lastAngle = startAngle;
			spinAdj = 0.0;
		}
		curAngle = Math.Atan2(e.Y - startY, e.X - startX);
		if (curAngle <= 0.0)
		{
			curAngle = Math.PI * 2.0 + curAngle;
		}
		if (lastAngle - curAngle > 3.0)
		{
			spinAdj += Math.PI * 2.0;
		}
		else if (lastAngle - curAngle < -3.0)
		{
			spinAdj -= Math.PI * 2.0;
		}
		lastAngle = curAngle;
		curDegrees = curAngle + spinAdj - startAngle;
		knobValue = (int)Math.Round((decimal)startValue + (decimal)knobRange * ((decimal)curDegrees / (decimal)(5.2359 * (double)((!FineMode) ? 1 : 3))));
		knobValue = knobValue / knobSteps * knobSteps;
		if (knobValue < knobMinimum)
		{
			knobValue = knobMinimum;
		}
		if (knobValue > knobMaximum)
		{
			knobValue = knobMaximum;
		}
		OnKnobChanged(EventArgs.Empty);
	}

	protected override void OnMouseUp(MouseEventArgs e)
	{
		shifted = false;
		thumbed = false;
		startArcX = -1;
	}

