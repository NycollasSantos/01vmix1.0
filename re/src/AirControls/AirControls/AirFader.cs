	{
		decimal num = faderValue;
		decimal num2 = 0m;
		int num3 = 0;
		if ((Control.MouseButtons & MouseButtons.Left) != 0 && thumbed)
		{
			if ((shifted || fineMode) && _valueType != "onoff")
			{
				num2 = ((!_horizontal) ? Math.Round(((decimal)travelSpace - ((decimal)startY - (decimal)(startY - e.Y) / 5m + (decimal)offsetY)) / ((decimal)travelSpace / faderRange) + (decimal)faderMinimum) : Math.Round(faderRange - ((decimal)travelSpace - ((decimal)startX - (decimal)(startX - e.X) / 5m + (decimal)offsetX)) / ((decimal)travelSpace / faderRange) + (decimal)faderMinimum));
			}
			else if (_horizontal)
			{
				num3 = e.X + offsetX;
				num2 = (decimal)(e.X + offsetX) / ((decimal)travelSpace / faderRange) + (decimal)faderMinimum;
			}
			else
			{
				num3 = e.Y + offsetY;
				num2 = ((!(ValueType == "fader")) ? ((decimal)(travelSpace - num3) / ((decimal)travelSpace / faderRange) + (decimal)faderMinimum) : ((decimal)(travelSpace - num3) / ((decimal)travelSpace / faderRange) + (decimal)faderMinimum));
			}
			faderValue = (int)Math.Round(num2 / (decimal)faderSteps) * faderSteps;
			if (faderValue < (decimal)faderMinimum)
			{
				faderValue = faderMinimum;
			}
			if (faderValue > (decimal)faderMaximum)
			{
				faderValue = faderMaximum;
