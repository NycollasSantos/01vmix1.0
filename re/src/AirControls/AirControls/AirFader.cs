	protected override void OnMouseDown(MouseEventArgs e)
	{
		thumbed = false;
		if (_horizontal)
		{
			startX = e.X;
			offsetX = XPos - e.X - travelLeft;
			if (startX >= travelLeft && startX < base.Width - travelRight)
			{
				thumbed = true;
			}
			if ((float)startX > (float)XPos - (float)base.Width / 24f - 8f && (float)startX < (float)XPos + (float)base.Width / 24f - 8f)
			{
				thumbed = true;
			}
		}
		else
		{
			startY = e.Y;
			offsetY = YPos - e.Y;
			if (startY >= travelTop && startY < base.Height - travelBottom)
			{
				thumbed = true;
			}
			if (startY > YPos + travelTop - 32 && startY < YPos + travelTop + 38)
			{
				thumbed = true;
			}
		}
		if ((Control.ModifierKeys & Keys.Shift) != 0)
		{
			shifted = true;
		}
		Focus();
	}

