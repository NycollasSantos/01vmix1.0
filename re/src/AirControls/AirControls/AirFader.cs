	protected override void OnMouseClick(MouseEventArgs e)
	{
		decimal num = faderValue;
		if (_horizontal)
		{
			if (e.X < travelLeft)
			{
				faderValue -= (decimal)faderSteps;
			}
			if (e.X > base.Width - travelRight)
			{
				faderValue += (decimal)faderSteps;
			}
		}
		else if (e.Y > base.Height - travelBottom)
		{
			if (_valueType == "fader" || _valueType == "busfader")
			{
				if (fineMode)
				{
					--faderValue;
				}
				else
				{
					faderValue -= 16m;
				}
			}
			else
			{
				faderValue -= (decimal)faderSteps;
			}
		}
		else if (e.Y < travelTop)
		{
			if (_valueType == "fader" || _valueType == "busfader")
			{
				if (fineMode)
				{
					++faderValue;
				}
				else
				{
					faderValue += 16m;
				}
			}
			else
			{
				faderValue += (decimal)faderSteps;
			}
		}
		if (faderValue > (decimal)faderMaximum)
		{
			faderValue = faderMaximum;
		}
		if (faderValue < (decimal)faderMinimum)
		{
			faderValue = faderMinimum;
		}
		if (faderValue != num)
		{
			OnFaderChanged(EventArgs.Empty);
		}
		base.OnMouseClick(e);
	}

	protected override void OnMouseDoubleClick(MouseEventArgs e)
	{
		decimal num = faderValue;
		if (_showKnob && _valueType == "pan" && e.Y < travelTop)
		{
			faderValue = 0m;
			if (faderValue != num)
			{
				OnFaderChanged(EventArgs.Empty);
			}
		}
		else
		{
			OnMouseClick(e);
		}
	}

	protected override bool IsInputKey(Keys keyData)
	{
		if (_horizontal)
		{
			return (keyData & Keys.KeyCode) switch
			{
				Keys.Right => true, 
				Keys.Left => true, 
				_ => base.IsInputKey(keyData), 
			};
		}
		return (keyData & Keys.KeyCode) switch
		{
			Keys.Up => true, 
			Keys.Down => true, 
			_ => base.IsInputKey(keyData), 
		};
	}

