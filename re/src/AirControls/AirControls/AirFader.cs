	protected override void OnKeyDown(KeyEventArgs e)
	{
		decimal num = faderValue;
		_ = ValueDB;
		if (_valueType == "fader")
		{
			if (e.KeyCode == Keys.Up)
			{
				++faderValue;
			}
			if (e.KeyCode == Keys.Down)
			{
				--faderValue;
			}
			if (e.KeyCode == Keys.Prior)
			{
				faderValue += 16m;
			}
			if (e.KeyCode == Keys.Next)
			{
				faderValue -= 16m;
			}
			if (e.KeyCode == Keys.Clear)
			{
				Value = FuzzyFind(dbMap, 0.00m);
			}
			if (e.KeyCode == Keys.Home)
			{
				Value = FuzzyFind(dbMap, 0.00m);
			}
			if (e.KeyCode == Keys.End)
			{
				faderValue = faderMinimum;
			}
			if (e.KeyCode == Keys.Insert)
			{
				faderValue = faderMaximum;
			}
			if (e.KeyCode == Keys.Delete)
			{
				faderValue = faderMinimum;
			}
		}
		else if (_valueType == "busfader")
		{
			if (e.KeyCode == Keys.Up)
			{
				++faderValue;
			}
			if (e.KeyCode == Keys.Down)
			{
				--faderValue;
			}
			if (e.KeyCode == Keys.Prior)
			{
				faderValue += 16m;
			}
			if (e.KeyCode == Keys.Next)
			{
				faderValue -= 16m;
			}
			if (e.KeyCode == Keys.Clear)
			{
				Value = FuzzyFind(dbMapBus, 0.00m);
			}
			if (e.KeyCode == Keys.Home)
			{
				Value = FuzzyFind(dbMapBus, 0.00m);
			}
			if (e.KeyCode == Keys.End)
			{
				faderValue = faderMinimum;
			}
			if (e.KeyCode == Keys.Insert)
			{
				faderValue = faderMaximum;
			}
			if (e.KeyCode == Keys.Delete)
			{
				faderValue = faderMinimum;
			}
		}
		else
		{
			if (e.KeyCode == Keys.Up || e.KeyCode == Keys.Right)
			{
				faderValue += (decimal)faderSteps;
			}
			if (e.KeyCode == Keys.Down || e.KeyCode == Keys.Left)
			{
				faderValue -= (decimal)faderSteps;
			}
			if (e.KeyCode == Keys.Prior)
			{
				if (faderRange >= 84m)
				{
					faderValue += (decimal)(faderSteps * 5);
				}
				else
				{
					faderValue += (decimal)(faderSteps * 2);
				}
			}
			if (e.KeyCode == Keys.Next)
			{
				if (faderRange >= 84m)
				{
					faderValue -= (decimal)(faderSteps * 5);
				}
				else
				{
					faderValue -= (decimal)(faderSteps * 2);
				}
			}
			if (e.KeyCode == Keys.Clear)
			{
				faderValue = (int)Math.Round(faderRange * 0.5m) + faderMinimum;
			}
			if (e.KeyCode == Keys.Home)
			{
				faderValue = (int)Math.Round(faderRange * 0.5m) + faderMinimum;
			}
			if (e.KeyCode == Keys.End)
			{
				faderValue = faderMinimum;
			}
			if (e.KeyCode == Keys.Insert)
			{
				faderValue = faderMaximum;
			}
			if (e.KeyCode == Keys.Delete)
			{
				faderValue = faderMinimum;
			}
			faderValue = faderValue / (decimal)faderSteps * (decimal)faderSteps;
		}
		if (faderValue > (decimal)faderMaximum)
		{
			faderValue = faderMaximum;
		}
		if (faderValue < (decimal)faderMinimum)
		{
			faderValue = faderMinimum;
		}
		if (faderValue != num)
		{
			OnFaderChanged(EventArgs.Empty);
		}
	}

